/**
 * Binary and minified file classification (#1173).
 *
 * Repositories contain files that must never be parsed as source: compiled
 * artefacts, images and vendored bundles, plus machine-generated single-line
 * output. Misclassifying them wastes parser time and produces meaningless
 * findings, so classification happens before parsing.
 *
 * The classifier is pure and bounded: it inspects the first 8 KiB and counts
 * newlines over the same window, so a huge file costs the same as a small one.
 */

import * as path from "path";

export type FileKind = "text" | "binary" | "minified" | "generated";

export interface FileClassification {
  kind: FileKind;
  /** Human-readable reasons, ordered by the check that decided the kind. */
  reasons: string[];
  /** Average line length in the inspected window, rounded down. */
  averageLineLength: number;
}

export const INSPECTION_WINDOW_BYTES = 8 * 1024;
export const MINIFIED_AVERAGE_LINE_LENGTH = 500;
export const MINIFIED_LINE_THRESHOLD = 2;

const GENERATED_MARKERS = [
  "@generated",
  "do not edit",
  "code generated by",
  "automatically generated",
  "this file was generated",
];

const GENERATED_SUFFIXES = [
  ".min.js",
  ".min.css",
  ".pb.go",
  ".g.dart",
  ".designer.cs",
  ".generated.ts",
];

const BINARY_EXTENSIONS = [
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".ico",
  ".woff",
  ".woff2",
  ".ttf",
  ".eot",
  ".pdf",
  ".zip",
  ".gz",
  ".wasm",
  ".node",
  ".so",
  ".dylib",
  ".dll",
  ".exe",
];

export function classifyFile(filePath: string, content: Buffer | string): FileClassification {
  const buffer = Buffer.isBuffer(content) ? content : Buffer.from(content, "utf8");
  const window = buffer.subarray(0, INSPECTION_WINDOW_BYTES);
  const extension = path.extname(filePath).toLowerCase();
  const lowerPath = filePath.toLowerCase();

  if (BINARY_EXTENSIONS.includes(extension)) {
    return { kind: "binary", reasons: [`extension ${extension} is a binary format`], averageLineLength: 0 };
  }

  if (window.includes(0)) {
    return { kind: "binary", reasons: ["NUL byte in the first 8 KiB"], averageLineLength: 0 };
  }

  const text = window.toString("utf8");
  const newlineCount = (text.match(/\n/g) ?? []).length;
  const averageLineLength = newlineCount === 0 ? text.length : Math.floor(text.length / (newlineCount + 1));

  if (GENERATED_SUFFIXES.some((suffix) => lowerPath.endsWith(suffix))) {
    return { kind: "generated", reasons: [`path suffix ${path.extname(lowerPath)} marks generated output`], averageLineLength };
  }

  const lowerText = text.toLowerCase();
  const marker = GENERATED_MARKERS.find((candidate) => lowerText.includes(candidate));
  if (marker) {
    return { kind: "generated", reasons: [`header marker "${marker}"`], averageLineLength };
  }

  if (newlineCount < MINIFIED_LINE_THRESHOLD && averageLineLength >= MINIFIED_AVERAGE_LINE_LENGTH) {
    return {
      kind: "minified",
      reasons: [`average line length ${averageLineLength} with ${newlineCount} newlines`],
      averageLineLength,
    };
  }

  return { kind: "text", reasons: [], averageLineLength };
}

/** True when the file should be skipped by source parsers. */
export function shouldSkipParsing(classification: FileClassification): boolean {
  return classification.kind !== "text";
}
